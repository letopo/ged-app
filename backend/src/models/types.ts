// backend/src/models/types.ts — types communs aux modèles typés.
import type { Attributes, InitOptions, Model, ModelAttributes, ModelStatic } from 'sequelize';

/** Registre passé à associate(models) par models/index.js. */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export type ModelRegistry = Record<string, ModelStatic<Model<any, any>>>;

/** Colonnes d'un modèle : tous les attributs déclarés, sauf les horodatages
 *  createdAt / updatedAt, que Sequelize ajoute lui-même (timestamps: true). */
export type ModelColumns<M extends Model> = ModelAttributes<M, Omit<Attributes<M>, 'createdAt' | 'updatedAt'>>;

/** Équivaut à Model.init(columns, options), mais vérifie que chaque attribut
 *  déclaré dans la classe a sa colonne (et inversement), horodatages exceptés.
 *  Les déclarer en colonne changerait leur définition (allowNull, _autoGenerated). */
export function initModel<M extends Model>(model: ModelStatic<M>, columns: ModelColumns<M>, options: InitOptions<M>): void {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  (model as any).init(columns, options);
}
